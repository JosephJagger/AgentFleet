// @vitest-environment jsdom
import {act,cleanup,fireEvent,render,renderHook,screen,waitFor} from '@testing-library/react';
import {afterEach,beforeEach,expect,it,vi} from 'vitest';
import {api} from './lib/api';
import {grokTurnSettings,useGrokPreferences,type GrokPreferences} from './lib/grok-preferences';
import {GrokControls} from './components/GrokControls';
vi.mock('./lib/api',()=>({api:{grokPreferences:vi.fn(),saveGrokPreferences:vi.fn()}}));
const catalog:GrokPreferences={revision:0,settings:{},options:[{id:'model',values:['grok-full','grok-small']},{id:'reasoning_effort',values:['low','high']}],models:[{id:'grok-full',name:'Full',efforts:['low','high']},{id:'grok-small',name:'Small',efforts:['low']}]};
beforeEach(()=>{vi.resetAllMocks();HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','');};HTMLDialogElement.prototype.close=function(){this.removeAttribute('open');};});
afterEach(()=>{cleanup();vi.useRealTimers();});
it('continuous progress does not abort or starve the first settings read',async()=>{
 let done!:(data:GrokPreferences)=>void;
 vi.mocked(api.grokPreferences).mockImplementation(()=>new Promise(resolve=>{done=resolve;}));
 const view=renderHook(({seq})=>useGrokPreferences('session',seq),{initialProps:{seq:1}});
 await waitFor(()=>expect(api.grokPreferences).toHaveBeenCalledTimes(1));
 const signal=vi.mocked(api.grokPreferences).mock.calls[0]![1]!;
 for(let seq=2;seq<50;seq++)view.rerender({seq});
 expect(signal.aborted).toBe(false);
 await act(async()=>done(catalog));
 expect(view.result.current.ready).toBe(true);
 expect(view.result.current.models).toEqual(catalog.models);
});
it('an older background response cannot overwrite a successfully saved model',async()=>{
 vi.useFakeTimers();vi.mocked(api.grokPreferences).mockResolvedValueOnce(catalog);
 const view=renderHook(({seq})=>useGrokPreferences('session',seq),{initialProps:{seq:1}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
 let stale!:(data:GrokPreferences)=>void;
 vi.mocked(api.grokPreferences).mockImplementationOnce(()=>new Promise(resolve=>{stale=resolve;}));
 view.rerender({seq:2});
 await act(async()=>{await vi.advanceTimersByTimeAsync(5000);});
 vi.mocked(api.saveGrokPreferences).mockResolvedValue({...catalog,revision:1,settings:{model:'grok-full'}});
 await act(async()=>view.result.current.save({model:'grok-full'}));
 await act(async()=>stale(catalog));
 expect(view.result.current.settings.model).toBe('grok-full');
});
it('a newer session sequence refetches saved mode immediately and does not repeat that read on the short poll',async()=>{
 vi.useFakeTimers();
 vi.mocked(api.grokPreferences).mockResolvedValueOnce({...catalog,revision:2,settings:{mode:'plan',model:'grok-full'}});
 const view=renderHook(({seq})=>useGrokPreferences('session',seq),{initialProps:{seq:1}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
 expect(view.result.current.settings).toEqual({mode:'plan',model:'grok-full'});
 expect(view.result.current.fresh).toBe(true);
 expect(grokTurnSettings(view.result.current)).toEqual({mode:'plan',model:'grok-full'});
 expect(api.grokPreferences).toHaveBeenCalledTimes(1);
 vi.mocked(api.grokPreferences).mockResolvedValueOnce({...catalog,revision:3,settings:{mode:'default',model:'grok-full'}});
 view.rerender({seq:2});
 await act(async()=>{await Promise.resolve();});
 expect(api.grokPreferences).toHaveBeenCalledTimes(2);
 expect(view.result.current.settings).toEqual({mode:'default',model:'grok-full'});
 expect(view.result.current.fresh).toBe(true);
 expect(grokTurnSettings(view.result.current)).toEqual({mode:'default',model:'grok-full'});
 await act(async()=>{await vi.advanceTimersByTimeAsync(5000);});
 expect(api.grokPreferences).toHaveBeenCalledTimes(2);
});
it('a session sequence change during an in-flight read is fetched again and is not sent as the old plan mode',async()=>{
 vi.useFakeTimers();
 let finishFirst!:(data:GrokPreferences)=>void;
 let finishSecond!:(data:GrokPreferences)=>void;
 vi.mocked(api.grokPreferences).mockImplementationOnce(()=>new Promise(resolve=>{finishFirst=resolve;}))
  .mockImplementationOnce(()=>new Promise(resolve=>{finishSecond=resolve;}));
 const view=renderHook(({seq})=>useGrokPreferences('session',seq),{initialProps:{seq:1}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
 expect(api.grokPreferences).toHaveBeenCalledTimes(1);
 view.rerender({seq:2});
 await act(async()=>{await Promise.resolve();});
 expect(api.grokPreferences).toHaveBeenCalledTimes(1);
 await act(async()=>{finishFirst({...catalog,revision:2,settings:{mode:'plan',model:'grok-full'}});});
 expect(api.grokPreferences).toHaveBeenCalledTimes(2);
 expect(view.result.current.settings).toEqual({mode:'plan',model:'grok-full'});
 expect(view.result.current.fresh).toBe(false);
 expect(grokTurnSettings(view.result.current)).toBeUndefined();
 await act(async()=>{finishSecond({...catalog,revision:3,settings:{mode:'default',model:'grok-full'}});});
 expect(view.result.current.settings).toEqual({mode:'default',model:'grok-full'});
 expect(view.result.current.fresh).toBe(true);
 expect(grokTurnSettings(view.result.current)).toEqual({mode:'default',model:'grok-full'});
 await act(async()=>{await vi.advanceTimersByTimeAsync(5000);});
 expect(api.grokPreferences).toHaveBeenCalledTimes(2);
});
it('refetches immediately when a plan exit sequence arrives during an older read',async()=>{
 vi.useFakeTimers();
 const old:GrokPreferences={revision:2,settings:{mode:'plan'},options:[]};
 const fresh:GrokPreferences={revision:3,settings:{mode:'default'},options:[]};
 vi.mocked(api.grokPreferences).mockResolvedValueOnce(old);
 const view=renderHook(({seq})=>useGrokPreferences('session',seq),{initialProps:{seq:1}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
 let resolveOld!:(value:GrokPreferences)=>void;
 vi.mocked(api.grokPreferences).mockImplementationOnce(()=>new Promise(resolve=>{resolveOld=resolve;})).mockResolvedValue(fresh);
 view.rerender({seq:2});
 expect(api.grokPreferences).toHaveBeenCalledTimes(2);
 view.rerender({seq:3});
 await act(async()=>{resolveOld(old);});
 await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
 expect(api.grokPreferences).toHaveBeenCalledTimes(3);
 expect(view.result.current.settings.mode).toBe('default');
 expect(view.result.current.fresh).toBe(true);
});
it('a delayed save reply cannot restore plan after a newer plan-exit snapshot',async()=>{
 vi.useFakeTimers();
 const old:GrokPreferences={revision:1,settings:{mode:'plan'},options:[]};
 const saved:GrokPreferences={revision:2,settings:{mode:'plan',effort:'high'},options:[]};
 const exited:GrokPreferences={revision:3,settings:{mode:'default',effort:'high'},options:[]};
 vi.mocked(api.grokPreferences).mockResolvedValueOnce(old).mockResolvedValue(exited);
 const view=renderHook(({seq})=>useGrokPreferences('session',seq),{initialProps:{seq:1}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
 let finishSave!:(value:GrokPreferences)=>void;
 vi.mocked(api.saveGrokPreferences).mockImplementationOnce(()=>new Promise(resolve=>{finishSave=resolve;}));
 let saving!:Promise<void>;
 await act(async()=>{saving=view.result.current.save(saved.settings!);});
 view.rerender({seq:2});
 await act(async()=>{await Promise.resolve();});
 expect(view.result.current.settings.mode).toBe('default');
 expect(view.result.current.fresh).toBe(true);
 await act(async()=>{finishSave(saved);await saving;});
 expect(view.result.current.settings.mode).toBe('default');
 expect(grokTurnSettings(view.result.current)?.mode).toBe('default');
});
it('a delayed save is not stamped fresh while a plan-exit read is still pending',async()=>{
 vi.useFakeTimers();
 const old:GrokPreferences={revision:1,settings:{mode:'plan'},options:[]};
 const saved:GrokPreferences={revision:2,settings:{mode:'plan',effort:'high'},options:[]};
 vi.mocked(api.grokPreferences).mockResolvedValueOnce(old).mockImplementation(()=>new Promise(()=>{}));
 const view=renderHook(({seq})=>useGrokPreferences('session',seq),{initialProps:{seq:1}});
 await act(async()=>{await vi.advanceTimersByTimeAsync(1);});
 let finishSave!:(value:GrokPreferences)=>void;
 vi.mocked(api.saveGrokPreferences).mockImplementationOnce(()=>new Promise(resolve=>{finishSave=resolve;}));
 let saving!:Promise<void>;
 await act(async()=>{saving=view.result.current.save(saved.settings!);});
 view.rerender({seq:2});
 expect(view.result.current.fresh).toBe(false);
 await act(async()=>{finishSave(saved);await saving;});
 expect(grokTurnSettings(view.result.current)).toBeUndefined();
});
it('native model choices are usable before a first turn; incompatible effort is cleared on model change',async()=>{
 const onSave=vi.fn().mockResolvedValue(undefined);
 render(<GrokControls options={catalog.options} models={catalog.models} settings={{model:'grok-full',effort:'high'}} ready error="" onReload={()=>{}} onSave={onSave} disabled={false}/>);
 expect(screen.getByRole('button',{name:'Grok Build 设置'}).textContent).toContain('grok-full · high · 沿用原生');
 expect(screen.getByRole('button',{name:'Grok Build 设置'}).textContent).not.toContain('Grok Build ·');
 fireEvent.click(screen.getByRole('button',{name:'Grok Build 设置'}));
 const select=screen.getByLabelText('Grok Build 模型') as HTMLSelectElement;
 expect(select.disabled).toBe(false);
 expect(Array.from(select.options).map(o=>o.text)).toEqual(['沿用原生','Full','Small']);
 fireEvent.change(select,{target:{value:'grok-small'}});
 expect((screen.getByLabelText('Grok Build 思考强度') as HTMLSelectElement).value).toBe('');
 fireEvent.click(screen.getByRole('button',{name:'保存'}));
 await waitFor(()=>expect(onSave).toHaveBeenCalledWith({model:'grok-small',effort:undefined}));
});

