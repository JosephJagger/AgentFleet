import test from "node:test";
import assert from "node:assert/strict";
import {mkdtempSync,rmSync} from "node:fs";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {randomUUID} from "node:crypto";
import {ControlPlaneDatabase} from "./database-fixture.js";
import {loadConfig} from "../src/config.js";
import {GrokPreferencesService} from "../src/grok-preferences.js";
import {grokSettingsActive,parseGrokSettings,supportsGrokControls} from "../src/grok-settings.js";
import type {Principal} from "../src/auth.js";
test("Grok settings persist after reopening and only accept reported model ids",t=>{
 assert.equal(supportsGrokControls("0.30.117"),true);
 assert.equal(supportsGrokControls("0.30.116"),false);
 assert.equal(supportsGrokControls("0.30.114"),false);
 assert.equal(supportsGrokControls("0.31.0"),true);
 assert.equal(supportsGrokControls("1.0.0"),true);
 assert.equal(parseGrokSettings(undefined),undefined);
 assert.deepEqual(parseGrokSettings({}),{});
 assert.equal(grokSettingsActive({}),false);
 assert.equal(grokSettingsActive({permissionMode:"default"}),true);
 assert.equal(grokSettingsActive({permissionMode:"always",mode:"plan"}),true);
 assert.equal(parseGrokSettings({model:"grok-4.6",sandbox:"danger"}),undefined);
 const dir=mkdtempSync(join(tmpdir(),"grok-prefs-"));t.after(()=>rmSync(dir,{recursive:true,force:true}));
 const path=join(dir,"db.sqlite");let db=new ControlPlaneDatabase(path);t.after(()=>db.close());
 const cfg=loadConfig({AUTH_MODE:"password",ADMIN_EMAIL:"grok-prefs@example.test",ADMIN_PASSWORD:randomUUID(),DATABASE_PATH:path,PUBLIC_ORIGIN:"http://test",COOKIE_SECURE:"false"});
 const {workspaceId}=db.bootstrap(cfg);const at=new Date().toISOString();
 const user=db.get<{user_id:string}>("SELECT user_id FROM users LIMIT 1")!;
 const principal={workspaceId,userId:user.user_id} as Principal;
 db.run(`INSERT INTO machines(machine_id,workspace_id,public_key_spki,public_key_fingerprint,name,platform,platform_release,architecture,agent_version,identity_state,security_state,reachability,compatibility,capacity,created_at,updated_at) VALUES('m',?,'key','fingerprint','host','linux','24','x64','0.30.117','active','normal','online','compatible','idle',?,?)`,workspaceId,at,at);
 db.run(`INSERT INTO projects(project_id,workspace_id,machine_id,external_id,alias,canonical_root,identity_hash,provider,created_at,last_reported_at) VALUES('p',?,'m','p','project','/work','hash','grok',?,?)`,workspaceId,at,at);
 for(const id of ["s1","s2"])db.run(`INSERT INTO logical_sessions(logical_session_id,workspace_id,machine_id,project_id,title,managed,execution_state,reachability,created_at,updated_at) VALUES(?,?,'m','p','session',1,'idle','live',?,?)`,id,workspaceId,at,at);
 db.run(`INSERT INTO execution_segments(execution_segment_id,logical_session_id,machine_id,project_id,created_at) VALUES('seg','s1','m','p',?)`,at);
 const event=(seq:number,type:string,body:unknown)=>{
  const ref=`blob-${seq}`;
  db.run("INSERT INTO content_blobs(payload_ref,workspace_id,body_json,payload_hash,created_at,expires_at) VALUES(?,?,?,?,?,?)",ref,workspaceId,JSON.stringify(body),"hash",at,"9999-12-31T00:00:00Z");
  db.run(`INSERT INTO durable_events(event_id,payload_hash,source_kind,workspace_id,logical_session_id,execution_segment_id,machine_id,project_id,session_seq,projection_epoch,native_thread_id,type,schema_version,occurred_at,received_at,payload_ref,payload_state) VALUES(?,'hash','agent',?,'s1','seg','m','p',?,1,'native',?,'1',?,?,?,'present')`,`event-${seq}`,workspaceId,seq,type,at,at,ref);
 };
 let service=new GrokPreferencesService(db);
 assert.deepEqual(service.read(principal,"s1"),{settings:null,revision:0,options:[]});
 assert.deepEqual(service.write(principal,"s1",{settings:{permissionMode:"always"},revision:0}),{settings:{permissionMode:"always"},revision:1,options:[]});
 assert.throws(()=>service.write(principal,"s1",{settings:{permissionMode:"always"},revision:0}),{code:"SETTINGS_REVISION_CONFLICT"});
 assert.throws(()=>service.write(principal,"s1",{settings:{permissionMode:"bypass"},revision:1}),{code:"GROK_SETTINGS_INVALID"});
 event(1,"thread.started",{effectivePolicy:{configOptions:[{id:"model",options:["grok-4.6"],currentValue:"grok-4.6"},{id:"reasoning_effort",options:["low","high"],currentValue:"low"}]}});
 const reported=service.read(principal,"s1");
 assert.deepEqual(reported.options.find(option=>option.id==="model"),{id:"model",current:"grok-4.6",values:["grok-4.6"]});
 assert.throws(()=>service.write(principal,"s1",{settings:{model:"grok-other",permissionMode:"always"},revision:1}),{code:"GROK_OPTION_UNAVAILABLE"});
 assert.throws(()=>service.write(principal,"s1",{settings:{mode:'plan'},revision:1}),{code:'GROK_MODE_UNAVAILABLE'});
 assert.throws(()=>service.write(principal,"s1",{settings:{permissionMode:'auto'},revision:1}),{code:'GROK_PERMISSION_UNAVAILABLE'});
 db.run("UPDATE machines SET discovery_json=? WHERE machine_id='m'",JSON.stringify({agentRuntimes:{grok:{nativeManagement:true,grokControls:{planMode:true,permissionSync:true}}}}));
 const saved={model:"grok-4.6",effort:"high",permissionMode:"always" as const,mode:"plan" as const};
 assert.deepEqual(service.write(principal,"s1",{settings:saved,revision:1}).settings,saved);
 event(2,"turn.completed",{grokState:{mode:"plan",permissionRequested:"auto",permissionStatus:"requested"},configOptions:[{id:"model",options:["grok-4.7"],currentValue:"grok-4.7"}]});
 assert.deepEqual(service.read(principal,"s1").options.find(option=>option.id==="model")?.values,["grok-4.7"]);
 assert.equal(service.write(principal,"s1",{settings:saved,revision:2}).settings?.model,"grok-4.6");
 assert.throws(()=>service.write(principal,"s1",{settings:{...saved,model:"grok-missing"},revision:3}),{code:"GROK_OPTION_UNAVAILABLE"});
 assert.equal(service.read(principal,"s2").settings,null);
 assert.equal(service.read(principal,"s1").observed?.mode,"plan");
 assert.equal(service.read(principal,"s1").observed?.permissionStatus,"requested");
 assert.throws(()=>service.read({...principal,workspaceId:"other"},"s1"),{code:"SESSION_NOT_FOUND"});

 db.run("UPDATE machines SET discovery_json=? WHERE machine_id='m'",JSON.stringify({agentRuntimes:{grok:{models:[{id:'grok-current',name:'Native model',efforts:['low']}]}}}));
 assert.deepEqual(service.read(principal,"s2").options.find(o=>o.id==='model')?.values,['grok-current']);
 assert.deepEqual(service.write(principal,"s2",{revision:0,settings:{model:'grok-current',effort:'low'}}).settings,{model:'grok-current',effort:'low'});
 assert.throws(()=>service.write(principal,"s2",{revision:1,settings:{model:'grok-current',effort:'xhigh'}}),{code:'GROK_OPTION_UNAVAILABLE'});
 db.run("UPDATE machines SET discovery_json=NULL WHERE machine_id='m'");
 db.close();db=new ControlPlaneDatabase(path);service=new GrokPreferencesService(db);
 assert.equal(service.read(principal,"s1").settings?.model,"grok-4.6");
 assert.equal(service.read(principal,"s1").revision,3);
 db.run("UPDATE machines SET agent_version='0.30.114' WHERE machine_id='m'");
 assert.throws(()=>service.write(principal,"s1",{settings:saved,revision:3}),{code:"GROK_AGENT_UPDATE_REQUIRED"});
 db.run("UPDATE machines SET agent_version='0.30.117' WHERE machine_id='m'");
 db.run("UPDATE projects SET provider='codex' WHERE project_id='p'");
 assert.throws(()=>service.write(principal,"s1",{settings:saved,revision:3}),{code:"GROK_SESSION_REQUIRED"});
});
