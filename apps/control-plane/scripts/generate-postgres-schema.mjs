// Run after compiling. The reviewed snapshot is versioned independently from SQLite's historical migrations.
import { writeFileSync } from 'node:fs';
import { ControlPlaneDatabase } from '../dist/src/db.js';
const db = new ControlPlaneDatabase(':memory:');
try {
  const version = db.get('PRAGMA user_version').user_version;
  const tables = db.all("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name");
  const pending = new Map(tables.map(row => [row.name, row]));
  const ordered = [];
  while (pending.size) {
    const ready = [...pending.values()].filter(row => [...row.sql.matchAll(/REFERENCES\s+"?(\w+)"?/gi)].every(m => m[1] === row.name || !pending.has(m[1])));
    if (!ready.length) throw new Error('Cyclic schema dependency requires an explicit migration');
    for (const row of ready) { ordered.push(row); pending.delete(row.name); }
  }
  const identityColumns = [];
  const rowidTables = ['live_chat_messages', 'panel_voice_jobs', 'voice_transcripts', 'audit_entries'];
  const statements = ordered.map(row => {
    let sql = row.sql.replace(/\)\s*STRICT(?:\s*,\s*WITHOUT ROWID)?\s*$/i, ')').replace(/\bCOLLATE NOCASE\b/gi, '');
    sql = sql.replace(/(\w+) INTEGER PRIMARY KEY(?: AUTOINCREMENT)?/gi, (all, column) => {
      if (row.name === 'voice_deployment_guard') return `${column} BIGINT PRIMARY KEY`;
      identityColumns.push({ table: row.name, column });
      return `${column} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
    });
    sql = sql.replace(/\bINTEGER\b/g, 'BIGINT').replace(/\bTEXT\b/g, 'TEXT COLLATE "C"');
    sql = sql.replace(/REFERENCES\s+("?\w+"?)\s*\([\w,\s]+\)(?:\s+ON DELETE (?:CASCADE|SET NULL|RESTRICT))?/gi, '$& DEFERRABLE INITIALLY IMMEDIATE');
    if (rowidTables.includes(row.name)) {
      sql = sql.replace(/\)\s*$/, ', rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE)');
      identityColumns.push({ table: row.name, column: 'rowid' });
    }
    return sql;
  });
  statements.push(...db.all("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL ORDER BY name").map(row => row.sql));
  statements.push('CREATE UNIQUE INDEX users_email_folded ON users(af_ascii_fold(email))', 'CREATE UNIQUE INDEX pairing_code_folded ON pairing_transactions(af_ascii_fold(user_code))');
  writeFileSync(new URL('../src/postgres-baseline.json', import.meta.url), JSON.stringify({ sqliteVersion: version, version: 1, tables: tables.map(t => t.name), identityColumns, rowidTables, statements }, null, 2) + '\n');
} finally { db.close(); }
